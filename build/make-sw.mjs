// Writes web/sw.js: precaches every file of the app so it runs fully offline.
import fs from 'node:fs'; import path from 'node:path'; import crypto from 'node:crypto';
const root = path.resolve(import.meta.dirname, '../web');
const files = [];
(function walk(d) { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); if (fs.statSync(p).isDirectory()) walk(p); else if (f !== 'sw.js') files.push(path.relative(root, p)); } })(root);
const hash = crypto.createHash('sha1'); for (const f of files.sort()) hash.update(f).update(fs.readFileSync(path.join(root, f)));
const v = hash.digest('hex').slice(0, 10);
fs.writeFileSync(path.join(root, 'sw.js'), `// generated by build/make-sw.mjs
const CACHE = 'fitcrew-${v}';
const FILES = ${JSON.stringify(['./', ...files])};
self.addEventListener('install', (e) => e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())));
self.addEventListener('activate', (e) => e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((r) => r || fetch(e.request).catch(() => caches.match('./'))));
});
`);
console.log('sw.js', v, files.length, 'files');
