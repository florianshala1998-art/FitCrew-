// Copies the chosen Wikimedia Commons candidates into web/catalog/ and writes web/credits.js.
// usage: node build/pick-photos.mjs <candidate-dir> key=index ...
import fs from 'node:fs'; import path from 'node:path'; import { execFileSync } from 'node:child_process';
const [dir, ...picks] = process.argv.slice(2);
const out = path.resolve(import.meta.dirname, '../web/catalog'); fs.mkdirSync(out, { recursive: true });
const credits = {};
for (const p of picks) {
  const [key, idx] = p.split('=');
  const meta = JSON.parse(fs.readFileSync(path.join(dir, `${key}.json`), 'utf8'))[+idx];
  if (!meta) { console.error('no meta for', p); continue; }
  execFileSync('magick', [path.join(dir, `${key}_${idx}.jpg`), '-auto-orient', '-resize', '720x540^', '-gravity', 'center', '-extent', '720x540', '-strip', '-quality', '78', path.join(out, `${key}.jpg`)]);
  credits[key] = { title: meta.title.replace(/^File:/, ''), author: meta.artist || 'unbekannt', license: meta.license, url: meta.page };
}
fs.writeFileSync(path.resolve(out, '../credits.js'), '// generated by build/pick-photos.mjs – photos from Wikimedia Commons\nexport const CREDITS = ' + JSON.stringify(credits, null, 1) + ';\n');
console.log(Object.keys(credits).length, 'photos');
